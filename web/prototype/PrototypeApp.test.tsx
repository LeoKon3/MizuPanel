import '@testing-library/jest-dom/vitest'
import { act, cleanup, fireEvent, render, screen, waitFor, within } from '@testing-library/react'
import { afterEach, beforeEach, describe, expect, test, vi } from 'vitest'
import { PrototypeApp } from './PrototypeApp'

// Chart pixels are checked in Chrome; jsdom only exercises the real surrounding interactions.
vi.mock('recharts', () => ({
  ResponsiveContainer: ({ children }: { children: React.ReactNode }) => <div>{children}</div>,
  LineChart: () => <div>图表预览</div>, CartesianGrid: () => null, Line: () => null,
  XAxis: () => null, YAxis: () => null, Tooltip: () => null
}))

beforeEach(() => { history.replaceState(null, '', '/#/hosts'); localStorage.clear() })
afterEach(() => { cleanup(); vi.useRealTimers(); vi.unstubAllGlobals() })
const openNode = (name = 'node-a1') => fireEvent.click(screen.getByRole('button', { name }))

describe('isolated host workspace', () => {
  test('starts on the list without automatically selecting a host, keeping zero distinct from missing', () => {
    render(<PrototypeApp />)
    expect(screen.getByRole('heading', { level: 1 })).toHaveTextContent('主机')
    expect(screen.queryByRole('tab', { name: '进程' })).not.toBeInTheDocument()
    expect(within(screen.getByRole('button', { name: 'runner-01' }).closest('tr')!).getByText('0.0%')).toBeInTheDocument()
    expect(within(screen.getByRole('button', { name: 'edge-01' }).closest('tr')!).getAllByText('—')).toHaveLength(3)
    expect(screen.getByRole('button', { name: '打开 edge-01 终端' })).toBeDisabled()
  })
  test('restores the list filters after viewing a host', () => {
    render(<PrototypeApp />)
    fireEvent.change(screen.getByLabelText('搜索主机'), { target: { value: 'node' } })
    fireEvent.change(screen.getByLabelText('筛选分组'), { target: { value: '生产' } })
    openNode()
    fireEvent.click(screen.getByRole('button', { name: '返回主机列表' }))
    expect(screen.getByLabelText('搜索主机')).toHaveValue('node')
    expect(screen.getByLabelText('筛选分组')).toHaveValue('生产')
    expect(screen.getByText('显示 2 台，共 8 台')).toBeInTheDocument()
  })
  test('retains the process tab but resets process search when changing hosts', () => {
    render(<PrototypeApp />)
    openNode()
    fireEvent.click(screen.getByRole('tab', { name: '进程' }))
    fireEvent.change(screen.getByLabelText('搜索进程'), { target: { value: 'containerd' } })
    fireEvent.click(screen.getByRole('button', { name: '切换主机，当前 node-a1' }))
    fireEvent.click(screen.getByRole('button', { name: '切换到 node-a2' }))
    expect(screen.getByRole('tab', { name: '进程' })).toHaveAttribute('aria-selected', 'true')
    expect(screen.getByLabelText('搜索进程')).toHaveValue('')
    expect(screen.getByRole('heading', { level: 1 })).toHaveTextContent('node-a2')
    expect(location.hash).toBe('#/hosts/node-a2/processes')
    expect(screen.getByText('1501')).toBeInTheDocument()
    expect(screen.queryByText('1401')).not.toBeInTheDocument()
  })
  test('protects an unsaved file and never carries the old host draft to a new host', () => {
    render(<PrototypeApp />)
    openNode()
    fireEvent.click(screen.getByRole('tab', { name: '文件' }))
    fireEvent.change(screen.getByLabelText('/etc/mizupanel/notes.txt'), { target: { value: 'node-a1 private draft' } })
    fireEvent.click(screen.getByRole('button', { name: '切换主机，当前 node-a1' }))
    fireEvent.click(screen.getByRole('button', { name: '切换到 node-a2' }))
    expect(screen.getByRole('dialog', { name: '有未保存的修改' })).toBeInTheDocument()
    fireEvent.click(screen.getByRole('button', { name: '继续编辑' }))
    expect(screen.getByLabelText('/etc/mizupanel/notes.txt')).toHaveValue('node-a1 private draft')
    fireEvent.click(screen.getByRole('button', { name: '返回主机列表' }))
    fireEvent.click(screen.getByRole('button', { name: '丢弃并继续' }))
    openNode('node-a2')
    fireEvent.click(screen.getByRole('tab', { name: '文件' }))
    expect(screen.getByLabelText('/etc/mizupanel/notes.txt')).not.toHaveValue('node-a1 private draft')
    expect((screen.getByLabelText('/etc/mizupanel/notes.txt') as HTMLTextAreaElement).value).toContain('node-a2')
  })
  test('keeps AI drafts across drawer and workspace, pins context, and never makes a network call', () => {
    const fetch = vi.fn(() => { throw new Error('Prototype must not connect') })
    vi.stubGlobal('fetch', fetch)
    render(<PrototypeApp />)
    openNode()
    fireEvent.click(screen.getByRole('button', { name: 'AI 助手' }))
    expect(screen.getByText('上下文：node-a1')).toBeInTheDocument()
    fireEvent.change(screen.getByLabelText('发送给 AI 助手'), { target: { value: '不要重启，检查内存' } })
    fireEvent.click(screen.getByRole('button', { name: '关闭AI 运维助手' }))
    fireEvent.click(screen.getByRole('button', { name: '切换主机，当前 node-a1' }))
    fireEvent.click(screen.getByRole('button', { name: '切换到 node-a2' }))
    fireEvent.click(screen.getByRole('button', { name: 'AI 助手' }))
    expect(screen.getByLabelText('发送给 AI 助手')).toHaveValue('不要重启，检查内存')
    expect(screen.getByText('上下文：node-a1')).toBeInTheDocument()
    fireEvent.click(screen.getByRole('button', { name: '打开完整工作台' }))
    expect(screen.getByLabelText('发送给 AI 助手')).toHaveValue('不要重启，检查内存')
    fireEvent.click(screen.getByRole('button', { name: '预览发送' }))
    expect(screen.getByLabelText('发送给 AI 助手')).toHaveValue('')
    expect(screen.getByText(/已在本地预览你的问题，上下文为 node-a1/)).toBeInTheDocument()
    expect(fetch).not.toHaveBeenCalled()
  })
  test('selection clears when the visible target scope changes', () => {
    render(<PrototypeApp />)
    fireEvent.click(screen.getByLabelText('选择当前主机'))
    expect(screen.getByText('已选 8 台')).toBeInTheDocument()
    fireEvent.change(screen.getByLabelText('筛选分组'), { target: { value: '生产' } })
    expect(screen.queryByText(/已选 \d 台/)).not.toBeInTheDocument()
    expect(screen.getByLabelText('选择当前主机')).not.toBeChecked()
  })
  test('error and empty states can recover without removing the navigation', () => {
    render(<PrototypeApp />)
    fireEvent.change(screen.getByLabelText('演示数据状态'), { target: { value: 'error' } })
    expect(screen.getByText('主机列表暂时无法加载')).toBeInTheDocument()
    expect(screen.getByRole('navigation', { name: '全局导航' })).toBeInTheDocument()
    fireEvent.click(screen.getByRole('button', { name: '重试' }))
    expect(screen.getByRole('button', { name: 'node-a1' })).toBeInTheDocument()
    fireEvent.change(screen.getByLabelText('演示数据状态'), { target: { value: 'empty' } })
    expect(screen.getByRole('heading', { level: 1 })).toHaveTextContent('主机 0')
    fireEvent.click(screen.getByRole('button', { name: '加载演示主机' }))
    expect(screen.getByText('显示 8 台，共 8 台')).toBeInTheDocument()
  })
  test('cancelling browser back keeps the original history entry and unsaved draft', async () => {
    render(<PrototypeApp />)
    openNode()
    fireEvent.click(screen.getByRole('tab', { name: '文件' }))
    fireEvent.change(screen.getByLabelText('/etc/mizupanel/notes.txt'), { target: { value: 'keep this draft' } })
    act(() => history.back())
    await screen.findByRole('dialog', { name: '有未保存的修改' })
    await waitFor(() => expect(location.hash).toBe('#/hosts/node-a1/files'))
    fireEvent.click(screen.getByRole('button', { name: '继续编辑' }))
    expect(screen.getByLabelText('/etc/mizupanel/notes.txt')).toHaveValue('keep this draft')
    act(() => history.back())
    await screen.findByRole('dialog', { name: '有未保存的修改' })
    await waitFor(() => expect(location.hash).toBe('#/hosts/node-a1/files'))
    fireEvent.click(screen.getByRole('button', { name: '丢弃并继续' }))
    expect(location.hash).toBe('#/hosts/node-a1/overview')
    expect(screen.queryByRole('dialog')).not.toBeInTheDocument()
  })
  test('theme has its own storage key and does not modify production preferences', () => {
    localStorage.setItem('theme', 'light')
    render(<PrototypeApp />)
    fireEvent.click(screen.getByRole('button', { name: '切换到深色主题' }))
    expect(document.documentElement.dataset.theme).toBe('dark')
    expect(localStorage.getItem('mizupanel-prototype-theme')).toBe('dark')
    expect(localStorage.getItem('theme')).toBe('light')
  })
  test('refresh preserves visible rows until the new snapshot is ready', () => {
    vi.useFakeTimers()
    render(<PrototypeApp />)
    fireEvent.click(screen.getByRole('button', { name: '刷新主机' }))
    expect(screen.getByRole('button', { name: 'node-a1' })).toBeInTheDocument()
    expect(screen.getByText('正在刷新…')).toBeInTheDocument()
    expect(screen.getByRole('button', { name: '刷新主机' })).toBeDisabled()
    act(() => { vi.advanceTimersByTime(500) })
    expect(screen.getByRole('button', { name: '刷新主机' })).toBeEnabled()
  })
  test('tabs support arrow keys without carrying the old target data', () => {
    render(<PrototypeApp />)
    openNode()
    fireEvent.keyDown(screen.getByRole('tab', { name: '概览' }), { key: 'ArrowRight' })
    expect(screen.getByRole('tab', { name: '进程' })).toHaveAttribute('aria-selected', 'true')
    expect(screen.getByRole('tab', { name: '进程' })).toHaveFocus()
  })
  test('pending refresh cannot override an explicitly selected error state', () => {
    vi.useFakeTimers()
    render(<PrototypeApp />)
    fireEvent.click(screen.getByRole('button', { name: '刷新主机' }))
    fireEvent.change(screen.getByLabelText('演示数据状态'), { target: { value: 'error' } })
    act(() => { vi.advanceTimersByTime(1000) })
    expect(screen.getByText('主机列表暂时无法加载')).toBeInTheDocument()
  })
})
